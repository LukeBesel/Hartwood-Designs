"""Data file for the tablet production planner (production/planner/data.js) from the kit reports and supply data.

    .venv/bin/python tools/make_planner_data.py
"""
from __future__ import annotations

import csv
import json
import math
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, os.path.join(ROOT, 'engine'))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from hartwood import config as C  # noqa: E402
import make_supply as MS  # noqa: E402

KITS = ['blaster', 'dragon', 'floral']
DEFECTS = [
    # (id, label, where it is found, source)
    ('mechanism', 'Mechanism does not work (wheel, trigger, jaw, lid, music)', 'test step / customer', 'review Pareto #1'),
    ('tight', 'Part too tight or too loose', 'pop-out check / customer', 'review Pareto #2'),
    ('broken', 'Part broke (in the sheet or while building)', 'pop-out check / customer', 'review Pareto #3'),
    ('instructions', 'Instructions unclear or wrong', 'customer', 'review Pareto #4'),
    ('missing', 'Part or extra missing from the box', 'packing check / customer', 'review Pareto'),
    ('uncut', 'Not cut through / part stuck in the sheet', 'unload', 'production'),
    ('bridge', 'Bridge too strong or part fell out', 'unload', 'production'),
    ('burn', 'Burn marks or smoke stains on show faces', 'unload', 'production'),
    ('warp', 'Warped or wrong-thickness sheet', 'loading', 'production'),
    ('color', 'Wrong color / print misaligned', 'unload', 'production'),
    ('packing', 'Packing or shipping damage', 'customer', 'production'),
]


def main():
    out = {'generated': '2026-10-12', 'color_mode': C.COLOR_MODE, 'kits': {}, 'items': {}, 'defects': [], 'settings': {
        'shift_start': '08:00', 'shift_hours': 8, 'efficiency': 0.85, 'swap_min_per_job': C.SHEET_SWAP_S / 60.0,
        'hands_on_min': MS.HANDS_ON_MIN, 'sheets_per_job': C.SHEETS_PER_JOB}}
    for kit in KITS:
        rep = json.load(open(os.path.join(ROOT, 'kits', kit, f'{kit}_report.json')))
        steps = json.load(open(os.path.join(ROOT, 'kits', kit, f'{kit}_steps.json')))
        _, _, rows = MS.kit_bom(kit)
        bom = {}
        for i, q, note in rows:
            key = i if i != 'sheet_color' else 'sheet_color'
            bom[key] = round(bom.get(key, 0) + q, 4)
        jobs = []
        for j in rep['jobs']:
            kps = min(j['kits_per_sheet'])          # one run of this job serves this many kits
            jobs.append({'job': j['job'], 'sheets': j['sheets'], 'laser_min': j['laser_min'], 'kits_per_run': kps,
                         'file': f"kits/{kit}/cutfiles/{j['job']}_bed.lbrn2"})
        sheets = [{'letter': s['sheet'], 'color': s['color'], 'label': C.MATERIALS[s['color']]['label'], 'tile': s['tile'],
                   'fraction': s['fraction']} for s in rep['sheets']]
        pr = None
        prp = os.path.join(ROOT, 'kits', kit, 'print_mode', f'{kit}_report.json')
        if os.path.exists(prp):
            p = json.load(open(prp))
            pr = {'print_min': p['print']['print_minutes'], 'sides': p['print']['printed_sheet_sides'],
                  'laser_min': p['cut_minutes_per_kit'], 'sheets': len(p['sheets'])}
        out['kits'][kit] = {'name': steps['name'], 'price': steps['price'], 'pieces': steps['piece_count'],
                            'laser_min_per_kit': rep['cut_minutes_per_kit'], 'jobs': jobs, 'sheets': sheets, 'bom': bom,
                            'print_mode': pr, 'aliases': [kit, steps['name'].lower(), steps['name'].lower().replace(' ', '-')]}
    rp = {r[0]: r for r in csv.reader(open(os.path.join(ROOT, 'supply', 'reorder_points.csv')))}
    for k, it in MS.ITEMS.items():
        r = rp.get(it['name'])
        out['items'][k] = {'name': it['name'], 'unit': it['unit'], 'cost': it['cost'], 'lead_days': it['lead_days'],
                           'pack': it['pack'], 'reorder_at': int(r[4]) if r else 0, 'order_qty': int(r[5]) if r else it['pack'],
                           'suppliers': [{'name': s[0], 'price': s[1], 'status': s[2]} for s in it['suppliers']]}
    out['weekly_plan'] = MS.WEEKLY_PLAN
    out['defects'] = [{'id': a, 'label': b, 'found': c, 'source': d} for a, b, c, d in DEFECTS]
    os.makedirs(os.path.join(ROOT, 'production', 'planner'), exist_ok=True)
    with open(os.path.join(ROOT, 'production', 'planner', 'data.js'), 'w') as fh:
        fh.write('// generated by tools/make_planner_data.py, do not edit by hand\nwindow.HW_DATA = ')
        json.dump(out, fh, indent=1)
        fh.write(';\n')
    print('planner data written')


if __name__ == '__main__':
    main()
